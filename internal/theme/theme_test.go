// One ready-to-use preset per site type (FR-004; data-model.md "Theme Preset").
func TestPresetsForType_OnePerSiteType(t *testing.T) {
	for _, siteType := range []string{"profile", "log", "docs"} {
		presets := theme.PresetsForType(siteType)
		if len(presets) == 0 {
			t.Errorf("PresetsForType(%q): want at least one ready-to-use preset, got none", siteType)
			continue
		}
		for _, p := range presets {
			if p.SiteType != siteType {
				t.Errorf("PresetsForType(%q): preset %q has SiteType %q, want %q", siteType, p.ID, p.SiteType, siteType)
			}
			if p.ID == "" {
				t.Errorf("PresetsForType(%q): preset has an empty ID", siteType)
			}
		}
	}
}

// tokens.css generation must be deterministic and owned solely by biblio-cli
// (data-model.md "Theme Preset" validation rules).
func TestGenerateTokensCSS_Deterministic(t *testing.T) {
	presets := theme.PresetsForType("profile")
	if len(presets) == 0 {
		t.Fatal(`PresetsForType("profile"): want at least one preset to generate from`)
	}
	preset := presets[0]

	first, err := theme.GenerateTokensCSS(preset)
	if err != nil {
		t.Fatalf("GenerateTokensCSS() first call: %v", err)
	}
	second, err := theme.GenerateTokensCSS(preset)
	if err != nil {
		t.Fatalf("GenerateTokensCSS() second call: %v", err)
	}
	if first != second {
		t.Errorf("GenerateTokensCSS() is not deterministic for the same preset:\nfirst:\n%s\nsecond:\n%s", first, second)
	}

	if !strings.Contains(first, ":root") {
		t.Errorf("GenerateTokensCSS() output missing a :root custom-property block:\n%s", first)
	}
	for name := range preset.Tokens {
		if !strings.Contains(first, "--"+name) {
			t.Errorf("GenerateTokensCSS() output missing custom property for token %q:\n%s", name, first)
		}
	}
}

// The quarterly tokens.css for the default typesetting is pinned to a
// golden file: every property in contracts/config-and-tokens.md
// "tokens.css", sorted, with the type scale computed in Go
// (specs/004-quarterly-site-type FR-021, FR-026; research.md R3).
func TestGenerateQuarterlyTokensCSS_DefaultsGolden(t *testing.T) {
	preset, _ := theme.PresetByID("quarterly-default")
	eff, err := theme.Resolve(preset, theme.Typesetting{})
	if err != nil {
		t.Fatal(err)
	}
	got, err := theme.GenerateQuarterlyTokensCSS(preset, eff)
	if err != nil {
		t.Fatalf("GenerateQuarterlyTokensCSS() error = %v", err)
	}
	want, err := os.ReadFile(filepath.Join("testdata", "quarterly-default.tokens.css"))
	if err != nil {
		t.Fatal(err)
	}
	if got != string(want) {
		t.Errorf("tokens.css differs from golden.\ngot:\n%s\nwant:\n%s", got, want)
	}
}

// Each override changes exactly the properties it maps to, and the header
// lists the overridden keys.
func TestGenerateQuarterlyTokensCSS_Overrides(t *testing.T) {
	preset, _ := theme.PresetByID("quarterly-default")
	ts, errs := theme.ParseTypesetting(map[string]any{
		"accent":    "#1e4fd7",
		"align":     "justify",
		"numerals":  "arabic",
		"grid":      "centered",
		"rules":     "none",
		"drop_caps": "raised",
		"lead_in":   "none",
		"fleurons":  true,
		"font_body": "Söhne",
		"base_size": "16px",
		"scale":     1.5,
	})
	if len(errs) > 0 {
		t.Fatal(errs)
	}
	eff, _ := theme.Resolve(preset, ts)
	got, err := theme.GenerateQuarterlyTokensCSS(preset, eff)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"/* Typesetting overrides from content/site.yaml: accent, align, base_size, drop_caps, fleurons, font_body, grid, lead_in, numerals, rules, scale */",
		"--color-accent: #1e4fd7;",
		"--ts-align: justify;",
		"--ts-hyphens: auto;",
		"--ts-numerals: decimal;",
		"--ts-grid-columns: minmax(0, 1fr) minmax(0, 6fr) minmax(0, 1fr);",
		"--ts-rule-width: 0;",
		"--ts-dropcap-lines: 3;",
		"--ts-dropcap-float: none;",
		"--ts-lead-in-variant: normal;",
		`--ts-fleuron: "❦";`,
		`--font-body: "Söhne", "Helvetica Neue", Arial, sans-serif;`,
		`--font-display: "Archivo", "Helvetica Neue", Arial, sans-serif;`,
		"--ts-base-size: 16px;",
		"--ts-step-1: 24px;",
		"--ts-step-2: 36px;",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("tokens.css missing %q:\n%s", want, got)
		}
	}
	if !strings.Contains(got, "--ts-dropcap-float: none;") {
		t.Error("raised caps must not float")
	}
	ts2, _ := theme.ParseTypesetting(map[string]any{"drop_caps": "drop"})
	eff2, _ := theme.Resolve(preset, ts2)
	drop, _ := theme.GenerateQuarterlyTokensCSS(preset, eff2)
	if !strings.Contains(drop, "--ts-dropcap-float: left;") || !strings.Contains(drop, "--ts-dropcap-lines: 3;") {
		t.Errorf("drop caps tokens wrong:\n%s", drop)
	}
}

// The other presets' tokens.css output is unchanged by the quarterly
// generator (FR-036).
func TestGenerateTokensCSS_OtherPresetsUnchanged(t *testing.T) {
	want := map[string]string{
		"profile-default": "/* Generated by biblio-cli from theme preset \"profile-default\". Do not edit by hand. */\n:root {\n  --color-accent: #2563eb;\n  --color-bg: #ffffff;\n  --color-fg: #1a1a1a;\n  --color-muted: #6b7280;\n  --font-body: \"Inter\", system-ui, sans-serif;\n  --font-heading: \"Inter\", system-ui, sans-serif;\n}\n",
	}
	for id, w := range want {
		p, _ := theme.PresetByID(id)
		got, err := theme.GenerateTokensCSS(p)
		if err != nil || got != w {
			t.Errorf("GenerateTokensCSS(%s) =\n%s\nwant\n%s (err %v)", id, got, w, err)
		}
	}
}
