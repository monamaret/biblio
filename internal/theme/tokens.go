// GenerateTokensCSS renders the :root custom-property block tokens.css
// consists of, from a Theme Preset's token definitions. Generation is
// deterministic — token names are emitted in sorted order — because
// tokens.css is generated once and owned solely by biblio-cli, then imported
// unchanged by both the site build and the future MCP App UI bundle
// (research.md "Theming ownership and artifact").
func GenerateTokensCSS(preset Preset) (string, error) {
	if len(preset.Tokens) == 0 {
		return "", fmt.Errorf("theme: preset %q has no token definitions", preset.ID)
	}

	names := make([]string, 0, len(preset.Tokens))
	for name := range preset.Tokens {
		names = append(names, name)
	}
	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by biblio-cli from theme preset %q. Do not edit by hand. */\n", preset.ID)
	b.WriteString(":root {\n")
	for _, name := range names {
		fmt.Fprintf(&b, "  --%s: %s;\n", name, preset.Tokens[name])
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// quarterlyGrids maps the `grid` setting to the column template of the
// page grid (margin, text, notes).
var quarterlyGrids = map[string]string{
	"asymmetric": "minmax(0, 2fr) minmax(0, 7fr) minmax(0, 3fr)",
	"centered":   "minmax(0, 1fr) minmax(0, 6fr) minmax(0, 1fr)",
}

var quarterlyRuleWidths = map[string]string{"none": "0", "hairline": "1px", "heavy": "3px"}

// GenerateQuarterlyTokensCSS renders a quarterly site's tokens.css from the
// preset's colors and font stacks plus the resolved typesetting values
// (specs/004-quarterly-site-type contracts/config-and-tokens.md
// "tokens.css"). Like GenerateTokensCSS it emits a single :root block of
// custom properties in sorted order, so unchanged settings give a
// byte-identical file; quarterly.css reads them and contains no values of
// its own. Every value here comes from a validated Effective field
// (research.md R9), never from free-form author text.
func GenerateQuarterlyTokensCSS(preset Preset, eff Effective) (string, error) {
	if preset.SiteType != "quarterly" {
		return "", fmt.Errorf("theme: preset %q is not a quarterly preset", preset.ID)
	}
	m := lengthPattern.FindStringSubmatch(eff.BaseSize)
	if m == nil {
		return "", fmt.Errorf("theme: invalid base size %q", eff.BaseSize)
	}
	base, _ := strconv.ParseFloat(m[1], 64)
	unit := m[2]

	tokens := map[string]string{}
	for name, value := range preset.Tokens {
		tokens[name] = value
	}
	tokens["color-accent"] = eff.Accent
	tokens["font-body"] = withFamily(eff.FontBody, preset.Tokens["font-body"])
	tokens["font-display"] = withFamily(eff.FontDisplay, preset.Tokens["font-display"])
	tokens["font-heading"] = tokens["font-display"]
	tokens["font-mono"] = withFamily(eff.FontMono, preset.Tokens["font-mono"])

	tokens["ts-base-size"] = eff.BaseSize
	for n := 1; n <= 5; n++ {
		tokens[fmt.Sprintf("ts-step-%d", n)] = num(math.Round(base*math.Pow(eff.Scale, float64(n))*1000)/1000) + unit
	}
	tokens["ts-leading"] = num(eff.Leading)
	tokens["ts-measure"] = eff.Measure
	tokens["ts-align"] = eff.Align
	tokens["ts-hyphens"] = map[string]string{"left": "manual", "justify": "auto"}[eff.Align]
	tokens["ts-grid-columns"] = quarterlyGrids[eff.Grid]
	tokens["ts-rule-width"] = quarterlyRuleWidths[eff.Rules]
	switch eff.DropCaps {
	case "drop":
		tokens["ts-dropcap-lines"], tokens["ts-dropcap-float"] = "3", "left"
	case "raised":
		tokens["ts-dropcap-lines"], tokens["ts-dropcap-float"] = "3", "none"
	default:
		tokens["ts-dropcap-lines"], tokens["ts-dropcap-float"] = "0", "none"
	}
	tokens["ts-lead-in-variant"] = map[string]string{"small_caps": "all-small-caps", "none": "normal"}[eff.LeadIn]
	tokens["ts-numerals"] = map[string]string{"roman": "upper-roman", "arabic": "decimal"}[eff.Numerals]
	tokens["ts-fleuron"] = "none"
	if eff.Fleurons {
		tokens["ts-fleuron"] = `"❦"`
	}

	names := make([]string, 0, len(tokens))
	for name := range tokens {
		names = append(names, name)
	}
	sort.Strings(names)

	overridden := "none"
	if len(eff.Overridden) > 0 {
		overridden = strings.Join(eff.Overridden, ", ")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by biblio-cli from theme preset %q. Do not edit by hand. */\n", preset.ID)
	fmt.Fprintf(&b, "/* Typesetting overrides from content/site.yaml: %s */\n", overridden)
	b.WriteString(":root {\n")
	for _, name := range names {
		fmt.Fprintf(&b, "  --%s: %s;\n", name, tokens[name])
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// withFamily puts family first in the preset's font stack, keeping the
// preset's fallbacks after it ("Söhne" + `"Archivo", Arial, sans-serif` →
// `"Söhne", Arial, sans-serif`). family has passed familyPattern, so it
// can be quoted safely.
func withFamily(family, presetStack string) string {
	fallbacks := presetStack
	if i := strings.Index(presetStack, ","); i >= 0 {
		fallbacks = strings.TrimSpace(presetStack[i+1:])
	}
	return fmt.Sprintf("%q, %s", family, fallbacks)
}
